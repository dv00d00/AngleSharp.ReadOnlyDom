var hotTagRanks = hotTags.Select((tag, index) => (tag, index)).ToDictionary(item => item.tag, item => item.index);

var check = args.Length == 2 && args[0].Equals("--check", StringComparison.Ordinal);
if ((!check && args.Length != 1) || (check && args.Length != 2))
{
    Console.Error.WriteLine("Usage: AngleSharp.ReadOnlyDom.TagGenerator [--check] <generated-file>");
    return 2;
}

var angleSharp = typeof(TagNames).Assembly;
var factoryType =
    angleSharp.GetType("AngleSharp.Html.HtmlElementFactory", throwOnError: true)
    ?? throw new InvalidOperationException("AngleSharp HtmlElementFactory was not found.");
var factory =
    factoryType.GetField("Instance", BindingFlags.Static | BindingFlags.NonPublic)?.GetValue(null)
    ?? throw new InvalidOperationException("AngleSharp HtmlElementFactory.Instance was not found.");
var create =
    factoryType.GetMethod("Create", BindingFlags.Instance | BindingFlags.Public)
    ?? throw new InvalidOperationException("AngleSharp HtmlElementFactory.Create was not found.");

using var document = new HtmlParser().ParseDocument(string.Empty);
var allTags = typeof(TagNames)
    .GetFields(BindingFlags.Public | BindingFlags.Static)
    .Where(field => field.FieldType == typeof(string))
    .Select(field => new Tag(field.Name, (string)field.GetValue(null)!))
    .GroupBy(tag => tag.Value, StringComparer.Ordinal)
    .Select(group => group.OrderBy(tag => tag.Constant, StringComparer.Ordinal).First())
    .Select(tag =>
    {
        var element = (IElement)create.Invoke(factory, [document, tag.Value, null, NodeFlags.None])!;
        var flags = element.Flags & ~(NodeFlags.HtmlMember | NodeFlags.SvgMember | NodeFlags.MathMember);
        return tag with { Flags = flags };
    })
    .ToArray();
var tags = allTags
    .Where(tag => tag.Flags != NodeFlags.None)
    .OrderBy(tag => tag.Value.Length)
    .ThenBy(tag => hotTagRanks.TryGetValue(tag.Value, out var rank) ? rank : int.MaxValue)
    .ThenBy(tag => tag.Value, StringComparer.Ordinal)
    .ToArray();
var knownNames = new[] { "#comment", "#document", "#text" }
    .Concat(GetStringConstants(typeof(TagNames)))
    .Concat(GetStringConstants(typeof(AttributeNames)))
    .Distinct(StringComparer.Ordinal)
    .OrderBy(name => name, StringComparer.Ordinal)
    .Select((name, id) => new KnownName(name, checked((ushort)id)))
    .ToArray();


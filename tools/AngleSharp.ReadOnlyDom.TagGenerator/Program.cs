string[] hotTags =
[
    "a",
    "span",
    "code",
    "p",
    "li",
    "div",
    "td",
    "dd",
    "dt",
    "hr",
    "tr",
    "ol",
    "img",
    "i",
    "ul",
    "button",
    "b",
    "pre",
